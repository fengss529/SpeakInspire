package com.hatio.speakinspire.service

/**
 * 成文的风格。
 *
 * ## 为什么风格是「写法」而不是「语气」
 *
 * 一开始想按语气分（克制 / 热烈 / 幽默），但那是润色层面的事，
 * 改几个词就能装出来，而且和这个 App 的用途没关系。
 *
 * 真正决定「这篇能不能用」的是**结构**：
 * 同样三段话，写成随感是「我这两天一直在想……」，
 * 写成观点文是「先给主张，再拆两条理由」，
 * 写成清单是「五个要点，每点一句」。
 * 用户选风格，其实是在选「这篇写出来之后拿去干什么」。
 *
 * ## 这四种覆盖了什么
 *
 * | 风格 | 写出来长什么样 | 什么时候用 |
 * |---|---|---|
 * | 随感 | 第一人称，顺着想，可以不给出结论 | 自己回看 |
 * | 观点文 | 开口一句主张，后面是论证链 | 发出去、跟人争 |
 * | 口播稿 | 短句，读起来顺口，没有长定语 | 拍之前先顺一遍 |
 * | 清单法 | 分点，每点一句结论加一句解释 | 讲方法、讲步骤 |
 *
 * ## 「口播稿」和「不写逐字稿」不冲突
 *
 * 这两件事容易被当成一件，但它们管的是不同阶段：
 *
 * - **不写逐字稿**约束的是**转选题**——那一阶段产出的是拍摄时要照着讲的
 *   意群短语骨架。给成段文字，用户就会念，念出来的短视频没有
 *   「他在讲自己的事」的感觉。
 * - **口播稿**是**成文**的一种风格：它是一篇读起来顺口的完整文章，
 *   用户可以在拍之前过一遍，也可以在别的场合用。
 *
 * 区别在「照着念的那一稿」和「写给自己看的顺口版」——
 * 前者代替了表达，后者只是让文字更适合出声。
 *
 * ## 风格可以改，规矩不能
 *
 * [instruction] 只描述**怎么写**。真正护着用户的那几条
 * （不改立场、不编事实、标来源）在 [Prompts.DRAFT_FORBIDDEN] 里，
 * 任何风格都必须带上，设置页以灰字只读展示。
 */
enum class DraftStyle(
    val id: String,
    /** 设置页与成文页 chip 上显示的名字。两个字，窄屏放得下 */
    val label: String,
    /** 一句话说清写出来是什么样 */
    val blurb: String,
    /** 什么时候该选它——比解释风格本身有用 */
    val bestFor: String,
    /** 注入 prompt 的风格段。只写怎么写，不写能说什么 */
    val instruction: String,
) {

    /**
     * 默认。
     *
     * 选它当默认不是因为它最好，而是因为**它对内容的要求最低**：
     * 不需要用户有明确主张，也不要求他给出方法，
     * 只是想清楚了就写下来。别的三种都要求素材里本来就有那个结构。
     */
    REFLECTIVE(
        id = "reflective",
        label = "随感",
        blurb = "第一人称，顺着想下去，可以不给出结论",
        bestFor = "只想把想法理清楚",
        instruction = """
【这一篇用「随感」的写法】
- 第一人称，像在跟自己说话。允许犹豫、允许没想完。
- 300-500 字。段落短，一段只说一件事。
- 不喊口号，不总结人生道理，不在结尾强行升华。
- 如果这件事你确实还没想明白，就停在没想明白的地方——
  不许替自己收一个漂亮的尾。
""".trimIndent(),
    ),

    /**
     * 最吃素材的一种。
     *
     * 它要求用户本来就有一个说得出口的主张。素材里没有主张时，
     * 模型只能编一个——所以这一种在 prompt 里明写了
     * 「主张也必须来自用户说过的话」。
     */
    ARGUMENT(
        id = "argument",
        label = "观点文",
        blurb = "开头一句明确主张，后面是可检验的论证",
        bestFor = "有判断，想说服别人",
        instruction = """
【这一篇用「观点文」的写法】
- 第一段就要有一句能被单独摘出来的主张。它必须来自用户说过的话，
  不许替他造一个新立场。
- 主张之后给论证：两条支持它的理由，加上一个反面（有人会怎么反驳，
  以及这个反驳为什么站不住或者部分成立）。
- 600-900 字。每段开头一句是这一段的结论，后面才是解释。
- **不许用「首先/其次/最后」串段落**——那不是在论证，是在列队。
  段与段之间要靠意思承接，不是靠序号。
""".trimIndent(),
    ),

    /**
     * 唯一一种「写给耳朵」的风格。
     *
     * 它对本 App 有额外风险：读起来太顺，用户就容易照着念。
     * 所以这里明写了「这不是给你念的稿子」，并且要求保留口语的毛边。
     */
    SPOKEN(
        id = "spoken",
        label = "口播稿",
        blurb = "短句，读起来顺口，像对着人说话",
        bestFor = "拍之前先顺一遍",
        instruction = """
【这一篇用「口播稿」的写法】
- 短句为主。一句话超过二十个字就断开。
- 口语：用「就是」「其实」「你看」这类词，允许不完整的句子。
- 不许有长定语、不许有一句话里套三个从句。念出来会喘不上气。
- 200-400 字，按「开口—展开—收住」三段走。
- **这不是给用户照着念的稿子**，是让他提前顺一遍的版本。
  所以保留口语的毛边，不要把话说得太圆——太圆就像广告词。
""".trimIndent(),
    ),

    /**
     * 结构最硬的一种。
     *
     * 适合「我踩过坑，想告诉别人怎么办」这类内容。
     * 不适合纯情绪或纯判断——把情绪拆成条目会显得很冷。
     */
    CHECKLIST(
        id = "checklist",
        label = "清单法",
        blurb = "分点讲，每点一句结论加一句解释",
        bestFor = "有方法，想让人照做",
        instruction = """
【这一篇用「清单法」的写法】
- 5-7 个点，每点两句话：先一句结论，再一句说明为什么或怎么做。
- **每个点必须用「1.」「2.」这样的序号开头**，序号写在段落正文里。
  输出是一段一段的 JSON，读者只能从你写进正文的序号看出这是分点的——
  没有序号，读起来就是一篇普通的散文。
- 每个点都必须具体到能被执行。「多练习」不算一条，
  「把上次卡住的那句话单独讲三遍」才算。
- 点与点之间不重复，也不许为了凑数量把一个点拆成两个。
- 开头一句交代这几点是干什么用的，结尾不加总结陈词。
""".trimIndent(),
    ),
    ;

    companion object {
        val DEFAULT: DraftStyle = REFLECTIVE

        /** 存档里的 id 可能来自旧版本或被改坏 → 静默回落到默认 */
        fun byId(id: String?): DraftStyle =
            entries.firstOrNull { it.id == id } ?: DEFAULT

        /**
         * 认不出来就返回 null。
         *
         * 用在「这篇是按哪种风格写的」这种场合：v5 之前的文章
         * [com.hatio.speakinspire.data.model.Article.styleId] 是空串，
         * 那时候还没有风格这回事，说它「是篇随感」是编的。
         */
        fun byIdOrNull(id: String?): DraftStyle? =
            entries.firstOrNull { it.id == id }
    }
}
