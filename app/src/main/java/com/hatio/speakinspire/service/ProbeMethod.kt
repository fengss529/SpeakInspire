package com.hatio.speakinspire.service

/**
 * 追问的方法学。
 *
 * ## 为什么追问要有「方法」可选
 *
 * 「追问」不是一个动作，是一类动作。同样是逼用户想清楚，
 * 问「依据是什么」和问「你当时具体做了什么」会把人带到完全不同的地方：
 *
 * | 方法 | 把用户往哪带 | 适合什么想法 |
 * |---|---|---|
 * | 苏格拉底 | 从含糊到具体 | 有观点但说不出理由 |
 * | 逐层逼问 | 从表面到根上 | 想听真话、不怕被顶 |
 * | 反方质询 | 从自说到自辩 | 判断、主张、是非题 |
 *
 * 用户记的东西本来就杂：有时是一句抱怨，有时是一个判断，
 * 有时是一段经历。用一种问法套所有内容，一半的情况会问得很别扭。
 *
 * ## 为什么从四种减到三种
 *
 * 原来还有「连续追问为什么」和「还原具体场景」。前者和「逐层逼问」
 * 说的是同一件事，后者跟苏格拉底式在实操上分不出差别——
 * 两个选项在设置页里摆着，用户得先读两遍说明才能选出一个
 * 其实结果差不多的。**选择过多本身就是负担。**
 *
 * 删掉的方法如果还留在旧存档里，[byId] 会静默回落到默认，不报错、不弹窗——
 * 用户升级完发现方法名变了，比看到一个「你选的方法不存在」的错更好受。
 *
 * ## 所有方法共享同一条禁区
 *
 * 换的只是**提问手法**，不是 AI 的权力边界。
 * 「不给结论、不给建议、不给替代方案」这条线，
 * 在三种方法里都必须成立——否则用户只要切到一个「宽松」的方法，
 * 就能拿到答案，整个追问阶段就退化成咨询了。
 *
 * 所以 [Prompts.probeSystem] 的结构是：
 * 共享禁区 + 差异化手法，而不是三份互不相干的全文。
 * 这样以后加第四种方法，不可能漏掉禁区。
 *
 * ## 手法可以改，禁区不能
 *
 * [instruction] 只是**默认手法**。用户可以在设置里把它改掉
 * （见 [com.hatio.speakinspire.data.repository.ProbeMethodStore.instructionOf]）——
 * 问法是很私人的东西：有人嫌苏格拉底太绕，有人嫌反方质询太冲，
 * 让他自己改比再给他几个选项更管用。
 *
 * 但禁区不在 [instruction] 里，它在 [Prompts.probeSystem] 的固定段落里，
 * 界面上以灰字只读展示。**改手法改不出权力。**
 */
enum class ProbeMethod(
    val id: String,
    /** 设置页显示的名字。这里可以长，用来说明它到底是什么 */
    val label: String,
    /**
     * 追问页顶栏用的短名。
     *
     * 顶栏那一行只剩一百多 dp，塞「逐层逼问（grill-me）」会被截成
     * 「逐层逼问（gril…」，看着像坏了。设置页仍用 [label]，
     * 因为那里有整行宽度，把别名说清楚更重要。
     */
    val shortLabel: String,
    /** 一句话说明它会怎么问 */
    val blurb: String,
    /** 什么时候该选它——比解释方法本身有用 */
    val bestFor: String,
    /** 默认手法。注入 prompt 的只有这一段，只描述怎么问，不描述能说什么 */
    val instruction: String,
) {

    /**
     * 默认方法。
     *
     * 选它当默认不是因为它最好，而是因为它**最不容易出错**：
     * 只要求把含糊处问具体，对任何题材都成立，
     * 不会像逐层逼问那样在遇到情绪化内容时显得咄咄逼人。
     */
    SOCRATIC(
        id = "socratic",
        label = "苏格拉底式",
        shortLabel = "苏格拉底式",
        blurb = "把含糊的词挑出来，问他到底指什么",
        bestFor = "有观点，但说不清理由",
        instruction = """
【这一轮用的方法：苏格拉底式追问】
每次只抓一个含糊处：用户这句话里最空洞的那个词，问他具体指什么。
示范：
- 用户说「我紧张」→「紧张的时候，身体上具体是什么感觉？」
- 用户说「效果不好」→「谁觉得不好？标准是什么？」
- 用户说「大家都这样」→「具体是谁？你亲眼见过吗？」
要点：**只问定义，不给定义**。他答得越具体，你越接近下一个含糊处。
""".trimIndent(),
    ),

    /**
     * 最狠的一种。
     *
     * 和苏格拉底的区别：苏格拉底是「换个角度照亮同一个点」，
     * 这个是**咬着同一个点不松口**，一层比一层难回答。
     * 用户选它，通常是自己也知道在回避什么。
     */
    GRILL(
        id = "grill",
        label = "逐层逼问（grill-me）",
        shortLabel = "逐层逼问",
        blurb = "咬住最弱的那一处不放，一层比一层难答",
        bestFor = "想听真话，不怕被顶",
        instruction = """
【这一轮用的方法：逐层逼问（grill-me）】
先在他整段话里挑出**最经不起推敲的那一处**，然后咬住它，一层一层往下逼。
- 每一问都必须比上一问更难回答。他不舒服是对的，说明碰到东西了。
- 他给的理由，就是下一问的靶子：「那这个理由本身站得住吗？」
- 他开始绕、开始重复、开始说「反正就是这样」——那正是要停在那儿的地方，
  直接问：「你刚才绕开了，是不是因为这块你自己也没底？」
- 一层一层剥，直到剥到他自己也没想过的地方。**不换话题，不给他台阶下。**
要点：**逼的是那句话，不是这个人**。不评价他，不趁机下判断，
只把问题一层层往更硬的地方推。他答不上来时，把问题收窄一点再问一次，
而不是换个软问题放他过去。
""".trimIndent(),
    ),

    DEVILS_ADVOCATE(
        id = "devils_advocate",
        label = "反方质询",
        shortLabel = "反方质询",
        blurb = "站到他对面，用一个具体的场景顶他一下",
        bestFor = "判断、主张、是非题",
        instruction = """
【这一轮用的方法：反方质询】
站到他对面，用一个具体的人或场景来顶他一下。
示范：
- 「有人会说，这不就是……吗？你怎么回应？」
- 「按你刚才说的，那些……的人又算什么？」
- 「要是反过来才是对的呢？你能举出一个反例吗？」
要点：**顶的是观点，不是人**。一次只顶一个点，顶完就停，等他回。
""".trimIndent(),
    ),
    ;

    companion object {
        val DEFAULT: ProbeMethod = SOCRATIC

        /**
         * 存档里的 id 可能来自旧版本或被改坏。
         *
         * 旧版本还有 `five_whys`（连续追问为什么）和 `star`（还原具体场景），
         * 两个都已经删了。**静默回落到默认**，不提示、不报错：
         * 用户升级完打开设置，看到方法名变了会疑惑一下；
         * 看到一个「你选的追问方式已不存在」的红条，会觉得整个 App 坏了。
         */
        fun byId(id: String?): ProbeMethod =
            entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}
