package com.hatio.speakinspire.service

/**
 * 追问的方法学。
 *
 * ## 为什么追问要有「方法」可选
 *
 * 「追问」不是一个动作，是一类动作。同样是逼用户想清楚，
 * 问「依据是什么」和问「你当时具体做了什么」会把人带到完全不同的地方：
 *
 * | 方法 | 把用户往哪带 | 适合什么想法 |
 * |---|---|---|
 * | 苏格拉底 | 从含糊到具体 | 有观点但说不出理由 |
 * | 连续五问 | 从现象到根因 | 复盘一件事为什么没做好 |
 * | 反方质询 | 从自说到自辩 | 判断、主张、是非题 |
 * | 还原场景 | 从概括到细节 | 经历、故事、具体的一次 |
 *
 * 用户记的东西本来就杂：有时是一句抱怨，有时是一个判断，
 * 有时是一段经历。用一种问法套所有内容，一半的情况会问得很别扭。
 *
 * ## 所有方法共享同一条禁区
 *
 * 换的只是**提问手法**，不是 AI 的权力边界。
 * 「不给结论、不给建议、不给替代方案」这条线，
 * 在四种方法里都必须成立——否则用户只要切到一个「宽松」的方法，
 * 就能拿到答案，整个追问阶段就退化成咨询了。
 *
 * 所以 [Prompts.probeSystem] 的结构是：
 * 共享禁区 + 差异化手法，而不是四份互不相干的全文。
 * 这样以后加第五种方法，不可能漏掉禁区。
 */
enum class ProbeMethod(
    val id: String,
    /** 设置页显示的名字 */
    val label: String,
    /** 一句话说明它会怎么问 */
    val blurb: String,
    /** 什么时候该选它——比解释方法本身有用 */
    val bestFor: String,
    /** 注入 prompt 的提问手法。只描述怎么问，不描述能说什么 */
    val instruction: String,
) {

    /**
     * 默认方法。
     *
     * 选它当默认不是因为它最好，而是因为它**最不容易出错**：
     * 只要求把含糊处问具体，对任何题材都成立，
     * 不会像「连续五问」那样在遇到情绪化内容时显得咄咄逼人。
     */
    SOCRATIC(
        id = "socratic",
        label = "苏格拉底式",
        blurb = "把含糊的词挑出来，问他到底指什么",
        bestFor = "有观点，但说不清理由",
        instruction = """
【这一轮用的方法：苏格拉底式追问】
每次只抓一个含糊处：用户这句话里最空洞的那个词，问他具体指什么。
示范：
- 用户说「我紧张」→「紧张的时候，身体上具体是什么感觉？」
- 用户说「效果不好」→「谁觉得不好？标准是什么？」
- 用户说「大家都这样」→「具体是谁？你亲眼见过吗？」
要点：**只问定义，不给定义**。他答得越具体，你越接近下一个含糊处。
""".trimIndent(),
    ),

    FIVE_WHYS(
        id = "five_whys",
        label = "连续追问为什么",
        blurb = "一层层往下问，直到碰到他没想过的地方",
        bestFor = "复盘一件事为什么没做成",
        instruction = """
【这一轮用的方法：连续问「为什么」】
沿着同一个方向往下钻，一层一层问为什么，直到碰到他自己也没想过的地方。
- 第一层：为什么会出现这个情况？
- 之后每层：针对他上一句回答里的原因，继续问「那又是为什么？」
- 钻到第三层还停在原地的，换一个方向：「这件事对你来说意味着什么？」
要点：**不跳层，不替他归因**。他给的原因越笼统，越要往下问一层。
""".trimIndent(),
    ),

    DEVILS_ADVOCATE(
        id = "devils_advocate",
        label = "反方质询",
        blurb = "站到他对面，用一个具体的场景顶他一下",
        bestFor = "判断、主张、是非题",
        instruction = """
【这一轮用的方法：反方质询】
站到他对面，用一个具体的人或场景来顶他一下。
示范：
- 「有人会说，这不就是……吗？你怎么回应？」
- 「按你刚才说的，那些……的人又算什么？」
- 「要是反过来才是对的呢？你能举出一个反例吗？」
要点：**顶的是观点，不是人**。一次只顶一个点，顶完就停，等他回。
""".trimIndent(),
    ),

    STAR(
        id = "star",
        label = "还原具体场景",
        blurb = "把概括的话拉回某一个具体时刻",
        bestFor = "经历、故事、具体的一次",
        instruction = """
【这一轮用的方法：还原具体场景】
用户说的多半是概括（「我总是搞砸」）。把话拉回某一个具体时刻。
跟进顺序：什么时候、在哪、在场有谁 → 他当时做了什么 → 结果怎样 → 他现在怎么看。
示范：
- 「『总是』——最近一次是哪一次？当时具体发生了什么？」
- 「那句话是你说的，还是别人说的？」
要点：**要细节，不要评价**。他开始评价的时候，把评价再问回细节。
""".trimIndent(),
    ),
    ;

    companion object {
        val DEFAULT: ProbeMethod = SOCRATIC

        /** 存档里的 id 可能来自旧版本或被改坏，一律回落到默认 */
        fun byId(id: String?): ProbeMethod =
            entries.firstOrNull { it.id == id } ?: DEFAULT
    }
}
