    /**
     * 转选题：拆角度。
     *
     * 只给标题 + 一句话理由，**不给完整骨架**——
     * 选择时凭的是「这个切入方式我有没有兴趣讲」，
     * 看完完整骨架反而更难决断，而且 3 套骨架在手机上读不完。
     */
    val ANGLE_SYSTEM_PROMPT = """
你要为同一篇文章设计 3 个不同的拍摄角度，供用户挑选。

【铁律：不写逐字稿】
用户的原话是「照着念就不练口语了」。你的产出是**拍摄骨架**，
用于提醒他自己讲什么，不是台词。

【角度必须真正不同】
不是换一个说法，而是换一种**切入方式**。例如：
- 讲自己的经历（用具体故事开头）
- 直接挑衅（开口就反问观众）
- 讲原理（从机制层面切入）

【每个给什么】
- title：角度的一句话概括
- rationale：为什么这个角度适合讲（帮用户判断，不是给他答案）
- kind：类型标签，如「经历」「挑衅」「原理」

【不要给】
- 完整骨架（选了角度之后才生成）
- 逐字稿
- 建议他改成别的观点

输出 JSON 数组，3 个元素。
""".trimIndent()

    /**
     * 转选题：生成完整骨架 + 手边的料。
     *
     * 关键词必须是**意群短语**，不是孤立词。
     * 孤立词（"稿子""卡住"）对组句本身就很困难的用户认知负荷过高；
     * 意群短语（"我提前准备了稿子"）是带语法的半句，垫高了起跳点，
     * 但仍然需要用户自己说。
     *
     * ## 素材为什么和骨架挤在同一次请求里
     *
     * 分开两次会有两套互不相干的素材：发芽给过一套，选题再编一套，
     * 而发芽那套是用户亲眼看过、认可过的。**同一次生成**才能让它
     * 优先复用已有的芽（见 `buildOutline` 的 `sprouts` 参数），
     * 不够的部分才新找。这也少一次等待、少一次点击。
     *
     * ## 素材为什么不能成句
     *
     * 一旦成段，用户就会照着念——而「照着念就不练口语了」
     * 是这个 App 的前提。所以素材是**一条一条的短句**，
     * 中间没有连接词，怎么接进自己的话里仍由用户决定。
     *
     * ## 无出处即丢弃
     *
     * 这条在 prompt 里要求，也在代码里强制
     * （[com.hatio.speakinspire.domain.MaterialKit.sanitize]）。
     * 模型编一个「某项研究显示」太容易了，而用户会当真讲出去。
     */
    val OUTLINE_SYSTEM_PROMPT = """
把选定的拍摄角度展开成 4 段骨架，并给出几条「手边的料」。

【结构（固定 4 段）】
1. 开场钩子 — 5-10秒
2. 展开/暴露症状 — 15-20 秒
3. 拆解/给方法 — 15-20 秒
4. 收尾互动 — 5-10 秒
总时长 30-60 秒。

【骨架怎么写】
每段给 2-4 个**意群短语**，不是孤立词：
  错：卡住 / 大脑空白 / 稿子
  对：我明明准备过 / 但张嘴就卡住 / 稿子上的字全忘了

意群短语是带语法的半句，垫高起跳点，但**仍然要用户自己说**。

【镜头提示】
每段可挂 1-3 个镜头提示，用不同图标标注：
- 停顿
- 看镜头
- 手势
- 放慢
真人露脸最容易出问题的不是词说不出来，而是表情和节奏是平的，
提示必须显眼到拍摄时余光就能看到。

【手边的料（materials）】
除骨架外，再给 3-6 条素材。作用是「讲的时候手边有料」，
**不是替他写稿**——所以每条都是短句，不带连接词，不成段。
四类，kind 只能写这四个词之一：
- 例子：一件具体的事，可以是生活里的。（可以没有出处）
- 数据：一个数。（**必须有出处**）
- 金句：别人说过的、能一句话立住的话。（**必须有出处**）
- 引用：书、文章、研究里的说法。（**必须有出处**）

出处写在 source：人名 + 作品名，或机构 + 年份，或事件 + 时间。
**没有把握就整条不要给——不许编书名、人名、数字、年份。**
一个编出来的百分比会被用户当成真的讲出去，那是这个功能最坏的结果。
宁可只给两条，也不许凑数。

出处必须是**别人能查到的形状**。以下这几种写法等于没有出处，不要用：
- 指向用户自己：「用户原文」「他自己说过的」「记录里的话」。
  引用自己说过的话不叫引用——那种内容本来就在骨架里，不该混进素材当别人的话。
- 没有具体来源的研究：「某项研究显示」「心理学认为」「有专家说」。
- 学科名当出处：「社会心理学」「传播学」——那是学科，不是出处。要写就写
  具体到某本书、某篇论文、某个人，写不出具体的就整条不给。

给不出出处时**不要编，也不要偷偷改标成「例子」蒙过去**。
但可以换个方向：用户自己的经历里有没有能当例子的具体事？
例子本来就不需要出处，而且比一句名人名言更像他自己会讲的话。
宁可三条都是这样的例子，也不许一条编出来的引用。

如果用户已经长过芽（【他自己长过的芽】），先看那里有没有能用的：
有出处的连接优先复用，那是他自己看过、认过的。

【绝对禁止】
- 不写逐字稿
- 不加「建议你说」「你可以这样表达」这类引导语
- 不改变用户文章的观点
- 不给没有出处的数据、金句、引用

【输出格式】
只输出这个 JSON，不要加解释：
{"sections":[{"title":"开场钩子","seconds":8,"goal":"这一段要让观众停下来","phrases":["我准备了整整两周","可我一上台就"],"cues":[{"icon":"停顿","text":"说完第一句停一秒"}]}],"materials":[{"kind":"例子","text":"...","source":""},{"kind":"数据","text":"...","source":"某某研究，2019"}]}
- sections 固定 4 段
- seconds 是整数，四段合计 30-60
- phrases 是意群短语，2-4 个
- cues 可以为空数组
- materials 3-6 条；没有把握的条目直接不写
""".trimIndent()
}

